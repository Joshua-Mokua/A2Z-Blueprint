"""scripts/generate_cbs_aggregates.py — CBS aggregate writer (v7.14 + v8.10).

Populates `cbs_data/*_aggregate.json` files that the v7.10/v7.11 FLEXCUBE
Anti-Corruption Layer aggregator (`utils/flexcube_aggregator.py`) reads
when mode=synthetic and aggregate files are present.

Without these files, the ACL falls back to hardcoded demo defaults inside
`flexcube_aggregator._loan_portfolio_demo_defaults()` etc. With these
files in place, `mode=synthetic` becomes a meaningful test environment
that mirrors what `mode=live` would return — same dict contract, same
field names, same aggregate values.

Two modes of operation:
    1. **Generative mode (default):** writes the same demo-defaults values
       as JSON files. Lets the ACL synthetic-tier path become exercisable
       without a real CBS data dump.
    2. **Computed mode (--from-cbs, v8.10):** if `cbs_data/customers.json`,
       `cbs_data/accounts.json`, and `cbs_data/transactions.json` are
       present (Joshua's local A2Z Blueprint CBS simulation: 700K
       customers, 1.2M accounts, 50K transactions, 35 branches),
       aggregates from them. Computes loan portfolio (gross outstanding,
       segment + IFRS 9 stage breakdown), deposit book (LDR, stability +
       product + segment breakdown), NPL (stage 3 + aging buckets),
       customer base (tenure + channel + KYC risk bands), and dormant
       accounts (dormancy bands + segment counts + reactivation potential
       + latent value). Falls back to generative mode with a clear
       message if any required source file is missing.

Outputs (5 files):
    cbs_data/loans_aggregate.json     — for fetch_loan_portfolio_aggregate()
    cbs_data/deposits_aggregate.json  — for fetch_deposit_book_aggregate()
    cbs_data/npl_aggregate.json       — for fetch_npl_aggregate()
    cbs_data/customer_aggregate.json  — for fetch_customer_base_aggregate()
    cbs_data/dormant_aggregate.json   — for fetch_dormant_accounts_aggregate()

Each file is byte-identical in shape to what the demo defaults return —
same keys, same string Decimals, same ordering. The ACL doesn't know or
care whether the values came from these generated files or from demo
defaults; it just stamps `data_source = "cbs_synthetic"` instead of
`data_source = "demo_defaults"`.

Usage:
    python -m scripts.generate_cbs_aggregates [--from-cbs] [--out PATH]

Exit codes:
    0 — all 5 files written successfully
    1 — write error
"""
